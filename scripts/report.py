def render_run(det, prb, score, journal, blockers):
    L = []
    w = L.append
    now = datetime.now(timezone.utc).strftime("%d %B %Y at %H:%M UTC")

    executed = [j for j in journal if j.get("resolution") == "executed"]
    degraded = [j for j in journal if j.get("resolution") == "degraded"]
    deferred = [j for j in journal if j.get("resolution") == "deferred"]

    w("# Your DITA-as-code setup: run report")
    w("")
    w("Generated by DAC v%s on %s." % (DAC_VERSION, now))
    w("")
    w("Everything below landed on the `dac/setup` branch. Your `main` branch was not touched. "
      "If you want none of it, delete the branch and nothing remains.")
    w("")
    w("**%d step(s) completed, %d degraded to a fallback, %d waiting on someone else.**"
      % (len(executed), len(degraded), len(deferred)))
    w("")

    w("## What works right now")
    w("")
    if not executed:
        w("Nothing was set up. See what is blocked, below.")
    for j in executed:
        w("### %s" % j.get("title", j.get("id")))
        w("")
        w(j.get("outcome", ""))
        if j.get("files"):
            w("")
            w("Files: %s" % ", ".join("`%s`" % f for f in j["files"][:8]))
        if j.get("prove"):
            w("")
            w("Prove it yourself:")
            w("")
            w("```bash")
            w(j["prove"])
            w("```")
        w("")

    if degraded:
        w("## What is degraded")
        w("")
        w("These work, but a lesser version was installed because the better option was not "
          "available. Each one names what an upgrade would buy, so you can decide whether it is "
          "worth asking for.")
        w("")
        for j in degraded:
            w("### %s" % j.get("title", j.get("id")))
            w("")
            w("**Installed instead:** %s" % j.get("outcome", ""))
            w("")
            if j.get("lost"):
                w("**What you are missing:** %s" % j["lost"])
                w("")
            if j.get("upgrade"):
                w("**To upgrade:** %s" % j["upgrade"])
                w("")

    w("## What is blocked")
    w("")
    if not blockers:
        w("Nothing. Everything that could be automated was.")
        w("")
    else:
        top = blockers[:3]
        if len(blockers) > 3:
            w("There are %d blockers. The three with the biggest impact are below; the rest are "
              "in `.dac/blockers/`." % len(blockers))
            w("")
        for b in top:
            w("### %s - %s" % (b.get("id"), b.get("what")))
            w("")
            w("| | |")
            w("|---|---|")
            w("| **What is missing** | %s |" % b.get("impact", b.get("what", "")))
            w("| **Why** | %s |" % b.get("why", ""))
            w("| **Who can unblock it** | %s |" % b.get("who", "unknown"))
            w("| **Cost** | %s |" % b.get("cost", "none"))
            w("| **Lane** | %s |" % b.get("lane", "yellow"))
            w("")
            if b.get("fix"):
                w("**How to fix it:** %s" % b["fix"])
                w("")
            if b.get("draft_message_path"):
                w("**A ready-to-send message is waiting at** `%s`. It names the exact setting and "
                  "explains that the access requested is read-only." % b["draft_message_path"])
                w("")
            if b.get("meanwhile"):
                w("**In the meantime:** %s" % b["meanwhile"])
                w("")

    w("## Monday morning")
    w("")
    actions = []
    for b in blockers[:2]:
        if b.get("draft_message_path"):
            actions.append("Send the message in `%s` to %s." % (b["draft_message_path"],
                                                                b.get("who", "the right person")))
        else:
            actions.append("Unblock %s: %s" % (b.get("id"), b.get("fix", "")))
    if executed:
        actions.append("Open a pull request from `dac/setup` and watch the checks run. "
                       "That is the whole loop in one go.")
    # Upgrading a degraded step is a real next action. Pulling suggestions from the score
    # is not, once setup has run: score.json was computed BEFORE these steps executed, so
    # it would tell the writer to add the very CI workflow this run just wrote.
    for j in degraded:
        if j.get("upgrade") and j["upgrade"].lower().startswith("none") is False:
            actions.append("%s: %s" % (j.get("title", j.get("id")), j["upgrade"]))
    if not executed:
        for item in score.get("work_order", [])[:2]:
            if item["actions"]:
                actions.append(item["actions"][0])
    for i, a in enumerate(actions[:3], 1):
        w("%d. %s" % (i, a))
    if executed:
        w("")
        w("Then re-run the audit to see your new score: `dac audit`. The score in "
          "`dac-audit.md` was measured before this run.")
    w("")
    w("Read `docs/RUNBOOK.md` for the day-to-day loop, and `docs/SETUP.md` if you are setting up "
      "a second machine.")
    w("")
    return "\n".join(L)


# --------------------------------------------------------------------------------------


def main(argv=None):
    ap = argparse.ArgumentParser(description="DAC report renderer")
    ap.add_argument("--root", default=".")
    ap.add_argument("--kind", choices=("audit", "run"), default="audit")
    ap.add_argument("--out")
    ap.add_argument("--quiet", action="store_true")
    args = ap.parse_args(argv)

    state = os.path.join(args.root, ".dac", "state")
    det = load(os.path.join(state, "detect.json"))
    prb = load(os.path.join(state, "probe.json"))
    sco = load(os.path.join(state, "score.json"))

    if args.kind == "audit":
        body = render_audit(det, prb, sco)
        default_out = os.path.join(args.root, "dac-audit.md")
    else:
        journal = []
        jpath = os.path.join(args.root, ".dac", "journal.jsonl")
        if os.path.isfile(jpath):
            with open(jpath, encoding="utf-8") as fh:
                for line in fh:
                    line = line.strip()
                    if line:
                        try:
                            journal.append(json.loads(line))
                        except ValueError:
                            pass
        # blockers.py writes a payload object; probe.py exposes a bare list. Accept both,
        # and surface only genuinely blocked items - degraded ones belong in their own
        # section, because listing them as blocked makes a successful run look failed.
        raw = load(os.path.join(state, "blockers.json"), required=False)
        if isinstance(raw, dict):
            blockers = raw.get("blocked", [])
        elif isinstance(raw, list):
            blockers = raw
        else:
            blockers = prb.get("blockers", [])
        body = render_run(det, prb, sco, journal, blockers)
        default_out = os.path.join(args.root, "dac-report.md")

    out = args.out or default_out
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(body.rstrip() + "\n")
    if not args.quiet:
        print("report: wrote %s (%d lines)" % (out, body.count("\n") + 1), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
