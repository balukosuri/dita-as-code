#!/usr/bin/env python3
"""DAC reporter - renders the two writer-facing documents.

  --kind audit   dac-audit.md   what you have, what it can reach, what is in the way
  --kind run     dac-report.md  what works now, what is degraded, what is blocked, Monday

Written for the floor case: a technical writer who has never used Git, works in a CCMS UI
or Oxygen, and holds no admin rights. Every instruction is either something they can do
alone, or is labelled with who has to do it.

Python 3.8+, standard library only.
"""

import argparse
import json
import os
import sys
from datetime import datetime, timezone

DAC_VERSION = "0.1.0"

ARCHETYPE_LABELS = {
    "A": "Native DITA on disk",
    "B": "API-brokered CCMS",
    "C": "Binary or proprietary format",
    "D": "Delivery-side platform",
    "E": "Server-side render service",
}

ARCHETYPE_MEANING = {
    "A": "Your content is already portable DITA sitting in files. This is the best possible "
         "starting point. Your editor being a desktop application that cannot be scripted does "
         "not matter, because nothing in this pipeline needs to drive your editor - it all happens "
         "after you save.",
    "B": "Your content lives inside a CCMS. The CCMS stays where you author, and Git becomes a "
         "mirror that gives you history, automated checking and an independent build. Worth "
         "knowing up front: no CCMS on the market syncs DITA source to Git, so the export bridge "
         "is something that has to be built rather than switched on.",
    "C": "Your content is not DITA - it is either a proprietary format or binary files. You can "
         "still get version control, automated builds, linting and automated publishing. You "
         "cannot get meaningful component-level diffs or DITA-style reuse, and it would be "
         "dishonest to imply otherwise.",
    "D": "You have a delivery platform that content gets published into. This is usually the "
         "easiest part of the chain to automate.",
    "E": "You have a server-side publishing engine. Instead of installing a toolkit and running "
         "it, your build calls that service and collects the result. In a lot of organisations "
         "this is the fastest route to automated publishing, because the licensed engine is "
         "already sitting on a server that nobody has connected to Git yet.",
}

LEVEL_PLAIN = {
    0: "Not happening at all",
    1: "Someone does it by hand",
    2: "There is a script, but a human has to run it",
    3: "It happens automatically",
    4: "It happens automatically and cannot be skipped",
}


def load(path, required=True):
    """Read a DAC state file, failing with an instruction rather than a traceback."""
    if not os.path.isfile(path):
        if required:
            raise SystemExit(
                "error: %s not found.\n"
                "       Run the audit first:  dac audit" % os.path.basename(path))
        return None
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except ValueError:
        raise SystemExit(
            "error: %s is corrupt and cannot be read.\n"
            "       This usually means a previous run was interrupted.\n"
            "       Delete the state directory and run the audit again:\n"
            "         rm -rf .dac/state && dac audit" % os.path.basename(path))
    except OSError as exc:
        raise SystemExit("error: cannot read %s: %s" % (path, exc))


def bar(score, ceiling, width=4):
    filled = "#" * score
    reachable = "-" * max(0, ceiling - score)
    blocked = "." * max(0, width - ceiling)
    return filled + reachable + blocked


