# audit report
# --------------------------------------------------------------------------------------


def render_audit(det, prb, score):
    L = []
    w = L.append
    now = datetime.now(timezone.utc).strftime("%d %B %Y at %H:%M UTC")

    w("# Your DITA ecosystem: audit")
    w("")
    w("Generated by the DITA-as-Code Kit (DAC) v%s on %s." % (DAC_VERSION, now))
    w("")
    w("Scanned: `%s`" % det.get("root", "?"))
    w("")
    w("This report describes what you have today and what it can realistically become. "
      "Nothing has been changed on your machine or in your files.")
    w("")

    # ---- no content: onboarding, not assessment --------------------------------------
    if det.get("onboarding_required"):
        w("## We could not find any documentation here")
        w("")
        w("This folder contains no documentation source that DAC recognises (%d file(s) "
          "scanned). **That is completely normal**, and it is not a problem with your setup. "
          "It almost always means one of four things."
          % det.get("inventory", {}).get("total_files", 0))
        w("")
        w("### 1. Your content lives in a CCMS")
        w("")
        w("If you author in Heretto, MadCap IXIA, RWS Tridion Docs, Adobe Experience Manager "
          "Guides or Paligo, then your content is on their server and there is genuinely "
          "nothing on your computer to find. This is the most common case.")
        w("")
        w("**What to do:** re-run and tell DAC which system you use. It will set up a "
          "scheduled export that copies your content here automatically, then build the "
          "pipeline around it. You keep authoring in the CCMS exactly as you do today - "
          "nothing about your writing changes.")
        w("")
        w("### 2. Your content is on a network share or in SharePoint")
        w("")
        w("**What to do:** copy the folder to your own computer first, then open that copy "
          "and run DAC again. Working directly on a network share is slow and unreliable for "
          "this, and Git does not behave well on one.")
        w("")
        w("### 3. Your content is in a different folder")
        w("")
        w("**What to do:** find the folder containing your `.ditamap` and `.dita` files and "
          "open that one instead. If you are not sure where it is, your editor's most "
          "recently opened project will tell you.")
        w("")
        w("### 4. Your content is in another Git repository")
        w("")
        w("**What to do:** clone it first, then run DAC inside the clone. If you have never "
          "cloned a repository, ask whoever set up your team's repository for the URL and "
          "for help with the first clone - it is a one-time step.")
        w("")
        w("> **Nothing below this point is a meaningful assessment of your setup.** DAC has "
          "nothing to measure yet. The scores exist only because the report always prints "
          "them; ignore them until DAC can see your content.")
        w("")

    # ---- the bottom line -------------------------------------------------------------
    w("## The bottom line")
    w("")
    arche = score.get("archetypes", [])
    pct = score.get("percent_of_ceiling", 0)
    total, ceil = score.get("total", 0), score.get("total_ceiling", 0)
    if not score.get("assessed", True):
        w("**There is nothing to score yet.** DAC found no documentation source in this "
          "folder, so the numbers below are placeholders rather than an assessment of your "
          "setup. Come back to them once DAC can see your content.")
        w("")
    else:
        w("Your setup scores **%d out of a reachable %d** (%.0f%%) across ten capability areas."
          % (total, ceil, pct))
        w("")
    if arche and score.get("assessed", True):
        w("Your situation is best described as %s. What that means for you is explained below."
          % " and ".join("**%s**" % ARCHETYPE_LABELS.get(a, a) for a in arche))
        w("")
    assessed = score.get("assessed", True)
    binding = score.get("binding_constraint") if assessed else None
    if binding:
        w("**The single thing most worth fixing is %s.** It has the largest gap between where you "
          "are and where you could be, weighted by how much it matters." % binding.lower())
    elif assessed:
        w("**There is no gap left to close.** Every axis is already at the ceiling your tools "
          "allow.")
    else:
        w("**The one thing to do next is tell DAC where your content is.** Everything else "
          "follows from that.")
    w("")

    # ---- honest note about what "reachable" means -------------------------------------
    if ceil < score.get("max_possible", 40):
        w("> The ceiling is %d rather than %d because some capabilities are genuinely out of "
          "reach with your current tools. Those limits are explained under each area rather than "
          "hidden in an average." % (ceil, score.get("max_possible", 40)))
        w("")

    # ---- what we found ----------------------------------------------------------------
    w("## What you have")
    w("")
    findings = [f for f in det.get("findings", []) if f["confidence"] in ("high", "medium")]
    content = [f for f in findings if f.get("kind", "content") == "content"]
    tools = [f for f in findings if f.get("kind") == "toolchain"]
    if not content:
        w("No documentation system was found in this folder. See the section above for what "
          "to do about it.")
        w("")
        if tools:
            w("DAC did find tooling installed on this machine, which is useful to know but says "
              "nothing about where your content is:")
            w("")
            for f in tools:
                for e in f["evidence"][:2]:
                    w("- %s - %s" % (f["display_name"], e["detail"]))
            w("")
    for f in content:
        w("### %s" % f["display_name"])
        w("")
        w("Confidence: **%s**. Classified as %s." % (
            f["confidence"],
            ", ".join("%s (%s)" % (ARCHETYPE_LABELS.get(a, a), a) for a in f["archetype"])))
        w("")
        w("How we know:")
        w("")
        for e in f["evidence"][:6]:
            samples = e.get("samples") or []
            hint = (" - for example `%s`" % samples[0]) if samples else ""
            w("- %s%s" % (e["detail"], hint))
        w("")
        for n in f.get("notes", []):
            w("> %s" % n)
            w("")

    dita = det.get("dita", {})
    if dita.get("maps") or dita.get("topics"):
        w("### Your DITA content at a glance")
        w("")
        w("| What | How many |")
        w("|---|---|")
        w("| DITA maps | %d |" % dita.get("maps", 0))
        w("| Bookmaps | %d |" % dita.get("bookmaps", 0))
        w("| Topics | %d |" % dita.get("topics", 0))
        w("| Conditional filter files (`.ditaval`) | %d |" % dita.get("ditavals", 0))
        w("| Files using content reuse (`conref`) | %d |" % dita.get("conref_files", 0))
        w("| Files using indirect links (`keyref`) | %d |" % dita.get("keyref_files", 0))
        w("| Taxonomy maps (`subjectScheme`) | %d |" % dita.get("subjectscheme_files", 0))
        w("")
        if dita.get("conref_files"):
            w("Content reuse is genuinely in use here. That matters, because element-level reuse "
              "is the main thing DITA does that lightweight formats like Markdown cannot "
              "replicate without custom preprocessing. It is a good reason to stay on DITA.")
            w("")

    # ---- archetype meaning ------------------------------------------------------------
    if arche:
        w("## What your situation means")
        w("")
        for a in arche:
            w("**%s (%s).** %s" % (ARCHETYPE_LABELS.get(a, a), a, ARCHETYPE_MEANING.get(a, "")))
            w("")

    # ---- the ten axes -----------------------------------------------------------------
    w("## Where you stand, area by area")
    w("")
    w("`#` is where you are, `-` is reachable with your current tools, `.` is out of reach.")
    w("")
    w("| Area | Score | | Status |")
    w("|---|---|---|---|")
    for a in score.get("axes", []):
        w("| %s | %d/%d | `%s` | %s |" % (a["label"], a["score"], a["ceiling"],
                                          bar(a["score"], a["ceiling"]),
                                          LEVEL_PLAIN.get(a["score"], a["level"])))
    w("")

    for a in score.get("axes", []):
        w("### %s - %d out of %d" % (a["label"], a["score"], a["ceiling"]))
        w("")
        w("*%s*" % a["question"])
        w("")
        for e in a.get("evidence", []):
            w("- %s" % e["why"])
        if a.get("ceiling_note"):
            w("")
            w("> %s" % a["ceiling_note"])
        if a.get("actions"):
            w("")
            w("To improve this:")
            w("")
            for act in a["actions"]:
                w("- %s" % act)
        w("")

    # ---- environment ------------------------------------------------------------------
    w("## Your machine")
    w("")
    w("| Tool | Status |")
    w("|---|---|")
    for r in prb.get("runtime", []):
        if r.get("present"):
            state = "present" + (" (%s)" % r["version"] if r.get("version") else "")
            if r.get("status") and r["status"] not in ("ok",):
                state += " - %s" % r["status"]
        else:
            state = "**missing**"
        w("| `%s` | %s |" % (r["name"], state))
    w("")

    egress = prb.get("egress", [])
    if any(e.get("verdict") not in (None, "ok", "skipped") for e in egress):
        w("### Network")
        w("")
        w("Some of what a docs pipeline needs to download is filtered or mirrored on your "
          "network. This matters because a blocked download usually looks like a random build "
          "failure rather than a policy decision.")
        w("")
        for e in egress:
            if e.get("verdict") in ("ok", "skipped", None):
                continue
            w("- **%s** - %s. %s" % (e["id"], e["verdict"], e.get("detail") or
                                     e.get("on_block", "")))
        w("")

    # ---- correctness hazards ----------------------------------------------------------
    warns = det.get("warnings", [])
    hi = [x for x in warns if x["severity"] in ("high", "medium")]
    if hi:
        w("## Things that could quietly go wrong")
        w("")
        w("These are not errors today. They are ways a pipeline can report success while "
          "producing the wrong output, which is far more dangerous than a failed build.")
        w("")
        for x in hi:
            w("- **%s** (%s) - %s" % (x["id"], x["severity"], x["text"]))
        w("")

    blockers = prb.get("blockers", [])
    if blockers:
        w("## What is in the way")
        w("")
        for b in blockers:
            w("### %s - %s" % (b["id"], b["what"]))
            w("")
            w("**Why:** %s" % b.get("why", ""))
            w("")
            w("**Fix:** %s" % b.get("fix", ""))
            w("")

    inc = det.get("incumbent", {})
    if inc.get("notes"):
        w("## What we will not touch")
        w("")
        w("You already have tooling in place. Anything set up from here will extend it rather "
          "than replace it.")
        w("")
        for n in inc["notes"]:
            w("- %s" % n)
        w("")

    w("## What happens next")
    w("")
    if score.get("work_order"):
        w("In priority order, weighted by impact:")
        w("")
        for i, item in enumerate(score["work_order"][:5], 1):
            w("%d. **%s** (%d/%d)" % (i, item["label"], item["score"], item["ceiling"]))
            for act in item["actions"][:2]:
                w("   - %s" % act)
        w("")
    w("Run `dac setup` to have this done for you. It works unattended on a `dac/setup` branch, "
      "never touches `main`, and stops only for the things that genuinely need another person.")
    w("")
    return "\n".join(L)


